import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: '/opt/microsoft/msedge/msedge', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/*', route => {
  const url = route.request().url();
  if (/lh3\.googleusercontent/.test(url)) return route.abort();
  return route.continue();
});
await page.goto(new URL('../code-animated.html', import.meta.url).href, { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.locator('#floating-dock-root a:visible').first().waitFor();
assert.equal(await page.locator('#floating-dock-root a:visible').count(), 5);
assert.equal(await page.locator('.dock-fallback').isVisible(), false);
const first = page.locator('#floating-dock-root a:visible').first();
const circle = first.locator(':scope > div');
assert.equal(Math.round((await circle.boundingBox()).width), 40);
await first.hover();
await page.waitForTimeout(650);
assert.ok((await circle.boundingBox()).width > 65, 'Hovered icon magnifies');
await circle.hover();
await first.focus();
await page.locator('#floating-dock-root').getByText('Sản Phẩm', { exact: true }).waitFor();
await page.waitForTimeout(300);
const dockBounds = await page.locator('#floating-dock-root > div:visible').boundingBox();
assert.ok(Math.abs(dockBounds.x + dockBounds.width / 2 - 720) < 3, 'Desktop dock centered');
await page.screenshot({ path: '/tmp/wnw-dock-desktop.png' });
await page.mouse.move(0, 0);
await page.evaluate(() => document.documentElement.classList.add('dark'));
await page.waitForTimeout(300);
const color = await page.locator('#floating-dock-root > div:visible').evaluate(el => getComputedStyle(el).backgroundColor);
assert.notEqual(color, 'rgb(249, 250, 251)');
await page.screenshot({ path: '/tmp/wnw-dock-dark.png' });
await page.evaluate(() => document.documentElement.classList.remove('dark'));
await page.emulateMedia({ reducedMotion: 'reduce' });
await first.hover();
await page.waitForTimeout(300);
assert.equal(Math.round((await circle.boundingBox()).width), 40, 'Reduced motion removes magnification');
await page.setViewportSize({ width: 390, height: 844 });
const toggle = page.getByRole('button', { name: 'Mở điều hướng', exact: true });
await toggle.click();
assert.equal(await page.locator('#floating-dock-root a:visible').count(), 5);
await page.screenshot({ path: '/tmp/wnw-dock-mobile.png' });
await page.keyboard.press('Escape');
assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
await toggle.click();
await page.locator('#floating-dock-root a:visible').filter({ has: page.locator('svg') }).nth(1).click();
assert.ok(page.url().endsWith('#services'));
assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
const mobileBounds = await page.locator('#floating-dock-root > div:visible').boundingBox();
assert.ok(mobileBounds.x >= 0 && mobileBounds.x + mobileBounds.width <= 390, 'Dock fits mobile viewport');
assert.deepEqual(errors, [], 'No runtime errors');
await browser.close();
console.log('PASS: desktop magnification, tooltips, dark mode, reduced motion, mobile menu, Escape, navigation, dock viewport bounds, runtime errors.');
