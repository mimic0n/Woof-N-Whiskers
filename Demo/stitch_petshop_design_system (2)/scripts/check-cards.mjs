import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({executablePath:'/opt/microsoft/msedge/msedge',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const page = await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(new URL('../code-animated.html',import.meta.url).href,{waitUntil:'domcontentloaded',timeout:60000});
const cards=page.locator('#flash-products > div');
assert.equal(await cards.count(),4);
assert.equal(await page.locator('#flash-cards-root').count(),0);
assert.equal(await cards.first().evaluate(el=>getComputedStyle(el).borderRadius),'25px');
assert.ok((await cards.first().locator('.card-head').evaluate(el=>getComputedStyle(el).backgroundImage)).includes('linear-gradient'));
assert.equal(await cards.first().evaluate(el=>getComputedStyle(el).boxShadow),'none');
await page.locator('#flash-sale').scrollIntoViewIfNeeded();
await page.locator('#flash-products img').evaluateAll(images=>Promise.all(images.map(img=>img.decode())));
const heading=cards.first().locator('.product-title');
assert.equal(await heading.evaluate(el=>getComputedStyle(el).fontSize),'17px');
const image=await cards.first().locator('img').boundingBox();
assert.ok(Math.abs(image.width-image.height)<2,'Square product photo');
const badge=page.locator('header button[title="Giỏ hàng"] span.bg-danger');
const count=Number(await badge.textContent());
await cards.first().getByRole('button').click();
assert.equal(Number(await badge.textContent()),count+1);
await page.waitForTimeout(1400);
await page.locator('#flash-sale').scrollIntoViewIfNeeded();
await page.screenshot({path:'/tmp/wnw-product-1663178758-desktop.png'});
await page.setViewportSize({width:390,height:844});
await cards.first().scrollIntoViewIfNeeded();
await page.screenshot({path:'/tmp/wnw-product-1663178758-mobile.png'});
const bounds=await cards.first().boundingBox();assert.ok(bounds.x>=0 && bounds.x+bounds.width<=390);
assert.equal(await page.locator('#floating-dock-root button:visible').count(),1);
assert.deepEqual(errors,[]);
await browser.close();console.log('PASS: reference card design, local images, gradient header, rounded corners, no black shadow, cart, mobile layout, Floating Dock, no runtime errors.');
